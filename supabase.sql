-- آرا: جدول محصولات و سیاست های امنیتی Supabase
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) > 0),
  description text not null default '', price text not null default '',
  image_url text not null default '' check (image_url = '' or image_url ~* '^https?://'),
  emoji text not null default '🦜', available boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.products enable row level security;
drop policy if exists "public read available products" on public.products;
create policy "public read available products" on public.products for select to anon, authenticated using (available = true);
-- فقط کاربری که app_metadata.role او admin است، اجازه تغییر دارد.
drop policy if exists "admins insert products" on public.products;
create policy "admins insert products" on public.products for insert to authenticated with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
drop policy if exists "admins update products" on public.products;
create policy "admins update products" on public.products for update to authenticated using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin') with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
drop policy if exists "admins delete products" on public.products;
create policy "admins delete products" on public.products for delete to authenticated using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
